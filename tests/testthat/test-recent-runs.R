test_that("recent CSV runs survive workspace clear and restore independently", {
  f <- prediction_flow_fixture()
  model <- tempfile(fileext = ".rds"); csv <- tempfile(fileext = ".csv")
  saveRDS(f$bundle, model); write.csv(head(iris), csv, row.names = FALSE)
  on.exit(unlink(c(model, csv)), add = TRUE)
  workbench_test_server(f$server, {
    prepared(f$bundle$prepared); begin_attempt(f$bundle$config); add_completed(f$bundle); finish_attempt("Completed")
    session$flushReact()
    training <- serialize(list(raw(), prepared(), result(), completed_runs(), attempts()), NULL)
    session$setInputs(wb_load = list(name = "flowers.rds", datapath = model, size = file.info(model)$size))
    expect_length(recent_runs(), 1)
    session$setInputs(wb_new_data = list(name = "answers.csv", datapath = csv, size = file.info(csv)$size), wb_predict = 1)
    expect_length(recent_runs(), 2)
    expect_match(output$wb_recent_items$html, "CSV evaluation", fixed = TRUE)
    expect_match(output$wb_recent_items$html, "Uploaded saved model", fixed = TRUE)
    id <- names(recent_runs())[1]
    expected <- serialize(list(prediction_data(), new_predictions(), prediction_report()), NULL)
    expect_identical(recent_runs()[[id]]$kind, "CSV evaluation")
    session$setInputs(wb_clear_saved = 1)
    expect_null(active_model()); expect_null(prediction_data()); expect_length(recent_runs(), 2)
    session$setInputs(wb_recent_id = id, wb_recent_restore = 1)
    expect_identical(task_flow(), "saved")
    expect_identical(active_model()$model_name, "flowers.rds")
    expect_identical(serialize(list(prediction_data(), new_predictions(), prediction_report()), NULL), expected)
    expect_match(output$wb_workspace_notice, "no files were re-uploaded", fixed = TRUE)
    expect_false(identical(active_model()$model, recent_runs()[[id]]$bundle$model))
    current <- serialize(list(active_model(), prediction_data(), new_predictions()), NULL)
    session$setInputs(wb_recent_clear = 1)
    expect_length(recent_runs(), 0)
    expect_identical(serialize(list(active_model(), prediction_data(), new_predictions()), NULL), current)
    session$setInputs(wb_predict = 2)
    id <- names(recent_runs())[1]
    session$setInputs(wb_recent_id = id, wb_recent_remove = 1)
    expect_length(recent_runs(), 0)
    expect_identical(serialize(list(active_model(), prediction_data(), new_predictions()), NULL), current)
    expect_identical(serialize(list(raw(), prepared(), result(), completed_runs(), attempts()), NULL), training)
    # Restoring a production run handles the client's purpose-update echo.
    session$setInputs(wb_csv_purpose = "predict", wb_predict = 3)
    id <- names(recent_runs())[1]
    expect_identical(recent_runs()[[id]]$run$purpose, "predict")
    session$setInputs(wb_clear_saved = 2, wb_csv_purpose = "evaluate")
    session$setInputs(wb_recent_id = id, wb_recent_restore = 2)
    expect_equal(nrow(new_predictions()), 6)
    session$setInputs(wb_csv_purpose = "predict")
    expect_equal(nrow(new_predictions()), 6)
    expect_null(prediction_report()$metrics)
    session$setInputs(wb_csv_purpose = "evaluate")
    expect_null(new_predictions())
  })
})
test_that("recent history is bounded and duplicate model uploads refresh one entry", {
  f <- prediction_flow_fixture()
  workbench_test_server(f$server, {
    for (i in 1:12) remember_recent(f$bundle, "Loaded model", key = paste0("key-", i))
    expect_length(recent_runs(), 10)
    expect_false(any(c("recent-1", "recent-2") %in% names(recent_runs())))
    expect_identical(names(recent_runs())[1], "recent-12")
    remember_recent(f$bundle, "Loaded model", key = "key-5")
    expect_length(recent_runs(), 10)
    expect_identical(names(recent_runs())[1], "recent-5")
    expect_null(active_model()); expect_null(result())
  })
})
