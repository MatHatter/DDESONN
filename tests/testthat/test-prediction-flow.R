test_that("loaded model and CSV have an explicit prediction step and provenance", {
  f <- prediction_flow_fixture()
  model <- tempfile(fileext = ".rds"); model2 <- tempfile(fileext = ".rds"); csv <- tempfile(fileext = ".csv")
  other <- f$bundle; other$model_name <- "different file"; saveRDS(other, model2)
  saveRDS(f$bundle, model); write.csv(head(iris, 8)[1:4], csv, row.names = FALSE)
  on.exit(unlink(c(model, model2, csv)), add = TRUE)
  shiny::testServer(f$server, {
    expect_false(action_states()$wb_predict)
    session$flushReact()
    before <- serialize(list(raw(), prepared()), NULL)
    messages <- new.env()
    session$sendInputMessage <- function(id, message) messages[[id]] <- message
    session$setInputs(wb_load = list(name = "flowers.rds", datapath = model, size = file.info(model)$size))
    expect_identical(active_model()$model_name, "flowers.rds")
    expect_match(output$wb_active_model, "flowers.rds", fixed = TRUE)
    expect_null(result())
    expect_length(completed_runs(), 0)
    expect_identical(serialize(list(raw(), prepared()), NULL), before)
    expect_false(exists("wb_hidden", envir = messages, inherits = FALSE))
    expect_match(output$wb_saved_evaluation, "Training")
    expect_match(output$wb_prediction_model_ui$html, "flowers.rds", fixed = TRUE)
    expect_match(output$wb_warm_start_summary, "previous fit requested 2", fixed = TRUE)
    expect_false(action_states()$wb_predict)
    weights <- serialize(active_model()$model, NULL)
    session$setInputs(wb_csv_purpose = "predict")
    session$setInputs(wb_new_data = list(name = "flowers.csv", datapath = csv, size = file.info(csv)$size))
    expect_null(new_predictions())
    expect_true(action_states()$wb_predict)
    expect_match(output$wb_prediction_status, "Run predictions", fixed = TRUE)
    session$setInputs(wb_predict = 1)
    expect_equal(nrow(new_predictions()), 8)
    expect_true(nzchar(output$wb_new_chart$src))
    expect_identical(output$wb_has_predictions, "yes")
    expect_match(output$wb_prediction_result_info, "flowers.rds · flowers.csv", fixed = TRUE)
    expect_match(output$wb_prediction_status, "Results are below", fixed = TRUE)
    expect_null(prediction_report()$metrics)
    expect_match(output$wb_prediction_accuracy_note, "Prediction-only mode", fixed = TRUE)
    expect_identical(serialize(active_model()$model, NULL), weights)
    # Rebinding the same model selector does not erase results.
    session$setInputs(wb_prediction_model = selected_saved())
    expect_equal(nrow(new_predictions()), 8)
    # A new CSV clears results, without modifying the loaded model.
    session$setInputs(wb_new_data = list(name = "replacement.csv", datapath = csv, size = file.info(csv)$size))
    expect_null(new_predictions()); expect_null(prediction_provenance())
    expect_identical(output$wb_has_predictions, "no")
    session$setInputs(wb_predict = 2)
    expect_match(output$wb_prediction_result_info, "replacement.csv", fixed = TRUE)
    first_id <- selected_saved()
    session$setInputs(wb_load = list(name = "another-model.rds", datapath = model2, size = file.info(model2)$size))
    expect_length(saved_models(), 2)
    expect_null(new_predictions())
    expect_identical(active_model()$model_name, "another-model.rds")
    session$setInputs(wb_prediction_model = first_id)
    expect_identical(active_model()$model_name, "flowers.rds")
    expect_null(new_predictions())
    expect_null(prediction_data())
    expect_false(action_states()$wb_predict)
    session$setInputs(wb_new_data = list(name = "flowers-again.csv", datapath = csv, size = file.info(csv)$size))
    session$setInputs(wb_predict = 3)
    expect_match(output$wb_prediction_result_info, "flowers.rds", fixed = TRUE)
    # Bad CSV schemas fail visibly and cannot leave stale downloadable results.
    write.csv(data.frame(wrong = 1:3), csv, row.names = FALSE)
    session$setInputs(wb_new_data = list(name = "wrong.csv", datapath = csv, size = file.info(csv)$size))
    session$setInputs(wb_predict = 4)
    expect_match(model_error(), "every saved predictor", fixed = TRUE)
    expect_null(new_predictions()); expect_false(action_states()$wb_new_download)
    expect_identical(serialize(active_model()$model, NULL), weights)
  })
})
test_that("extra epochs create a named new model without replacing the upload", {
  f <- prediction_flow_fixture()
  model <- tempfile(fileext = ".rds"); saveRDS(f$bundle, model)
  on.exit(unlink(model), add = TRUE)
  shiny::testServer(f$server, {
    session$setInputs(wb_load = list(name = "original.rds", datapath = model, size = file.info(model)$size))
    original_id <- selected_saved()
    original <- serialize(saved_models()[[original_id]], NULL)
    session$setInputs(wb_hidden = "99", wb_epochs = 500, wb_lr = .8)
    expect_identical(serialize(saved_models()[[original_id]], NULL), original)
    session$setInputs(wb_more_epochs = 1, wb_saved_checkpoint = "best_validation", wb_continue = 1)
    expect_equal(job()$epochs, 1)
    job()$process$wait(30000); session$elapse(400)
    expect_null(job()); expect_null(training_error())
    expect_identical(task_flow(), "saved")
    expect_identical(active_model()$model_name, "original.rds")
    expect_length(completed_runs(), 0)
    expect_null(result())
    expect_null(prepared())
    expect_true(any(vapply(recent_runs(), function(record) record$kind == "Further-trained saved model", logical(1))))
    expect_match(output$wb_saved_fit_status, "Completed", fixed = TRUE)
    expect_length(attempts(), 0)
    expect_null(training_context())
    expect_identical(serialize(saved_models()[[original_id]], NULL), original)
    expect_match(saved_fit()$bundle$model_name, "original.rds · extra fit", fixed = TRUE)
    expect_equal(saved_fit()$bundle$config$epochs, 1)
    expect_identical(saved_fit()$bundle$config$checkpoint, "best_validation")
    expect_equal(saved_fit()$bundle$config$lr, f$bundle$config$lr)
    expect_identical(saved_fit()$bundle$prepared, f$bundle$prepared)
    session$setInputs(wb_saved_use_fit = 1)
    expect_match(active_model()$model_name, "extra fit", fixed = TRUE)
    expect_length(saved_models(), 2)
    expect_null(result())
  })
})
test_that("binary and regression uploads render their prediction charts", {
  f <- prediction_flow_fixture()
  for (mode in c("binary", "regression")) {
    target <- if (mode == "binary") "am" else "mpg"
    p <- f$h$wb_prepare(mtcars, target, c("wt", "hp"), mode)
    invisible(capture.output(bundle <- f$h$wb_run(p, f$h$wb_config(hidden = "2", epochs = 1, checkpoint = "final"))))
    model <- tempfile(fileext = ".rds"); csv <- tempfile(fileext = ".csv")
    saveRDS(bundle, model); write.csv(head(mtcars, 4)[c("wt", "hp")], csv, row.names = FALSE)
    shiny::testServer(f$server, {
      session$setInputs(wb_load = list(name = paste0(mode, ".rds"), datapath = model, size = file.info(model)$size))
      session$setInputs(wb_csv_purpose = "predict")
      session$setInputs(wb_new_data = list(name = "cars.csv", datapath = csv, size = file.info(csv)$size), wb_predict = 1)
      expect_null(model_error())
      expect_equal(nrow(new_predictions()), 4)
      expect_true(nzchar(output$wb_new_chart$src))
      if (mode == "regression") expect_true(is.numeric(new_predictions()$prediction)) else
        expect_true(all(new_predictions()$predicted %in% c("0", "1")))
      session$setInputs(wb_csv_purpose = "evaluate")
      write.csv(head(mtcars, 4)[c("wt", "hp", target)], csv, row.names = FALSE)
      session$setInputs(wb_new_data = list(name = "labeled-cars.csv", datapath = csv, size = file.info(csv)$size), wb_predict = 2)
      expect_null(model_error())
      expect_true("actual" %in% names(new_predictions()))
      expect_true(nzchar(output$wb_new_chart$src))
      expect_match(output$wb_csv_primary_score, if (mode == "regression") "CSV RMSE:" else "CSV accuracy:", fixed = TRUE)
    })
    unlink(c(model, csv))
  }
})
