  })
})
test_that("evaluation is the default and requires known answers before showing accuracy", {
  f <- prediction_flow_fixture()
  model <- tempfile(fileext = ".rds"); csv <- tempfile(fileext = ".csv")
  saveRDS(f$bundle, model); write.csv(head(iris, 8)[1:4], csv, row.names = FALSE)
  on.exit(unlink(c(model, csv)), add = TRUE)
  shiny::testServer(f$server, {
    session$setInputs(wb_load = list(name = "flowers.rds", datapath = model, size = file.info(model)$size))
    expect_identical(csv_purpose(), "evaluate")
    session$setInputs(wb_new_data = list(name = "unlabeled.csv", datapath = csv, size = file.info(csv)$size))
    expect_false(action_states()$wb_predict)
    expect_match(output$wb_prediction_status, "Species", fixed = TRUE)
    session$setInputs(wb_predict = 1) # Server guard also rejects bypassed UI.
    expect_null(new_predictions()); expect_match(model_error(), "known correct answers", fixed = TRUE)
    write.csv(head(iris, 8), csv, row.names = FALSE)
    session$setInputs(wb_new_data = list(name = "labeled.csv", datapath = csv, size = file.info(csv)$size))
    expect_true(action_states()$wb_predict)
    session$setInputs(wb_predict = 2)
    expect_match(output$wb_csv_primary_score, "CSV accuracy:", fixed = TRUE)
    expect_match(output$wb_csv_primary_score, "%", fixed = TRUE)
    expect_match(output$wb_csv_result_title, "Evaluation", fixed = TRUE)
    expect_true("actual" %in% names(new_predictions()))
    expect_true(nzchar(output$wb_new_chart$src))
    # Explicit prediction mode never silently evaluates even if labels exist.
    session$setInputs(wb_csv_purpose = "predict")
    expect_null(new_predictions())
    session$setInputs(wb_predict = 3)
    expect_null(prediction_report()$metrics)
    expect_match(output$wb_csv_primary_score, "8 predictions generated", fixed = TRUE)
    expect_false("actual" %in% names(new_predictions()))
    session$setInputs(wb_csv_purpose = "evaluate")
    expect_null(new_predictions())
    expect_identical(csv_target_check()$valid, TRUE)
  })
})
