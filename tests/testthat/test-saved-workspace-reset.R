test_that("clear and exact-file reload reset saved data without touching training", {
  f <- prediction_flow_fixture()
  model <- tempfile(fileext = ".rds"); duplicate <- tempfile(fileext = ".rds"); csv <- tempfile(fileext = ".csv"); bad <- tempfile(fileext = ".rds")
  saveRDS(f$bundle, model); file.copy(model, duplicate); write.csv(head(iris), csv, row.names = FALSE); saveRDS(list(wrong = TRUE), bad)
  on.exit(unlink(c(model, duplicate, csv, bad)), add = TRUE)
  shiny::testServer(f$server, {
    prepared(f$bundle$prepared); begin_attempt(f$bundle$config); add_completed(f$bundle); finish_attempt("Completed")
    session$flushReact()
    original <- serialize(list(raw(), prepared(), result(), completed_runs(), attempts()), NULL)
    messages <- list()
    session$sendCustomMessage <- function(type, message) messages[[type]] <<- message
    upload <- list(name = "flowers.rds", datapath = model, size = file.info(model)$size)
    session$setInputs(wb_load = upload)
    session$setInputs(wb_new_data = list(name = "flowers.csv", datapath = csv, size = file.info(csv)$size), wb_predict = 1)
    expect_false(is.null(new_predictions()))
    session$setInputs(wb_load = list(name = "flowers.rds", datapath = duplicate, size = file.info(duplicate)$size))
    expect_length(saved_models(), 1)
    expect_null(prediction_data()); expect_null(prediction_source()); expect_null(new_predictions())
    expect_null(prediction_report()); expect_false(action_states()$wb_predict)
    expect_true("wb_new_data" %in% messages[["wb-reset-files"]]$ids)
    # A bad replacement is reported beside upload and retains the valid active model.
    session$setInputs(wb_load = list(name = "wrong.rds", datapath = bad, size = file.info(bad)$size))
    expect_identical(active_model()$model_name, "flowers.rds")
    expect_match(output$wb_load_error, "previous active model", fixed = TRUE)
    session$setInputs(wb_clear_saved = 1)
    expect_null(active_model()); expect_null(selected_saved()); expect_length(saved_models(), 0)
    expect_null(prediction_data()); expect_null(new_predictions()); expect_null(load_error())
    expect_identical(output$wb_has_saved_model, "no")
    expect_false(action_states()$wb_new_download); expect_false(action_states()$wb_predict)
    expect_setequal(messages[["wb-reset-files"]]$ids, c("wb_load", "wb_new_data"))
    expect_identical(serialize(list(raw(), prepared(), result(), completed_runs(), attempts()), NULL), original)
    session$setInputs(wb_load = upload)
    expect_length(saved_models(), 1); expect_identical(active_model()$model_name, "flowers.rds")
    expect_null(prediction_data())
  })
})
