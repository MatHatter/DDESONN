test_that("Shiny vignette links prefer installed guides and retain source fallbacks", {
  skip_if_not_installed("shiny")
  h <- new.env(parent = globalenv())
  sys.source(system.file("shiny", "benchmark", "helpers.R", package = "DDESONN"), h)
  source <- h$dashboard_vignettes("")
  expect_equal(nrow(source), 4)
  expect_false(any(source$local))
  expect_true(all(startsWith(source$href, "https://github.com/MatHatter/DDESONN/blob/main/vignettes/")))
  root <- tempfile(); dir.create(root)
  on.exit(unlink(root, recursive = TRUE), add = TRUE)
  file <- paste0(source$file[1], ".html")
  writeLines("<html><body>Benchmark guide</body></html>", file.path(root, file))
  links <- h$dashboard_vignettes(root)
  expect_equal(links$local, c(TRUE, FALSE, FALSE, FALSE))
  expect_identical(links$href[1], paste0("ddesonn-vignettes/", file))
  expect_identical(links$href[-1], source$href[-1])
  ui <- as.character(h$dashboard_vignettes_ui(root))
  on.exit(shiny::removeResourcePath("ddesonn-vignettes"), add = TRUE)
  expect_match(ui, 'target="_blank"', fixed = TRUE)
  expect_match(ui, 'rel="noopener noreferrer"', fixed = TRUE)
  expect_match(ui, file, fixed = TRUE)
})
