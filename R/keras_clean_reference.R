# Opt-in original-Keras clean-split protocol adapter. The ordinary SONN train/learn paths
# are unchanged. The research harness supplies the compiled float32 kernel.
.ddesonn_fit_keras_clean_reference <- function(member, x, y, parameters, moving,
                                       seed, average_gradients, kernel, n_train, n_validation, epochs = 360L) {
  reduction <- .ddesonn_gradient_reduction(average_gradients)
  stopifnot(inherits(member, "SONN"), isTRUE(member$ML_NN),
            identical(as.integer(member$hidden_sizes), c(64L, 32L)),
            ncol(x) == 12L, nrow(x) == 5000L, nrow(y) == 5000L,
            length(parameters) == 10L, length(moving) == 4L,
            is.function(kernel), all(is.finite(x)), all(y %in% c(0, 1)))
  # Shared initial tensors were generated by the unchanged archived Keras builder.
  member$weights <- parameters[c(1L, 5L, 9L)]
  member$biases <- lapply(parameters[c(2L, 6L, 10L)], function(v) matrix(v, ncol = 1L))
  result <- kernel(parameters, moving, x, y, as.integer(seed),
                   reduction == "mean", as.integer(n_train), as.integer(n_validation), as.integer(epochs))
  stopifnot(result$epochs == epochs, result$updates == epochs * ceiling(n_train / 16),
            all(is.finite(result$probability)), result$validation_steps == epochs * ceiling(n_validation / 16),
            length(result$validation_loss) == epochs, all(is.finite(result$validation_loss)))
  member$weights <- result$parameters[c(1L, 5L, 9L)]
  member$biases <- lapply(result$parameters[c(2L, 6L, 10L)], function(v) matrix(v, ncol = 1L))
  member$keras_reference_state <- list(parameters = result$parameters,
    moving = result$moving, accumulators = result$accumulators,
    average_gradients = average_gradients, epochs = result$epochs,
    updates = result$updates, checkpoint = "final", batch_size = 16L,
    precision = "float32", implementation = "opt-in native original-Keras clean-split protocol adapter")
  result
}
