library(DDESONN)
h <- new.env(parent = globalenv())
sys.source(system.file('shiny','benchmark','workbench_helpers.R',package='DDESONN'),h)
out <- Sys.getenv('DDESONN_MODEL_EXPORT', unset='/workspace/model-downloads/customer-segmentation-compact')
dir.create(out,recursive=TRUE,showWarnings=FALSE); setwd(out)
options(DDESONN_OUTPUT_ROOT=out); Sys.setenv(DDESONN_ARTIFACTS_ROOT=out)
original <- readRDS('/workspace/model-downloads/customer-segmentation/customer-segmentation-model-7.3.31.rds')
p <- unserialize(serialize(original$prepared,NULL))
# Same grouped splits/preprocessing, a distinctly smaller network.
cfg <- h$wb_config(hidden='16,8',epochs=100,lr=.003,optimizer='adam',checkpoint='best_validation')
log <- file.path(out,'training.log'); con<-file(log,'wt');sink(con)
bundle <- tryCatch(h$wb_run(p,cfg),finally={sink();close(con)})
bundle$model_name <- 'Customer segmentation — Compact 16x8'
bundle$history <- h$wb_log_history(log);bundle$training_log <- readLines(log,warn=FALSE)
name <- 'customer-segmentation-compact-16x8.rds'
saveRDS(bundle,file.path(out,name),compress='xz')
loaded <- h$wb_validate_bundle(readRDS(file.path(out,name)))
stopifnot(file.info(file.path(out,name))$size<50*1024^2,!identical(bundle$config$hidden,original$config$hidden))
d <- read.csv(system.file('extdata','train_multiclass_customer_segmentation.csv',package='DDESONN'),check.names=FALSE)
labeled <- d[head(p$parts$test$row,20),c(p$features,p$target)]
write.csv(labeled,file.path(out,'compact-original-test-example.csv'),row.names=FALSE,na='')
unlabeled <- read.csv(system.file('extdata','test_multiclass_customer_segmentation.csv',package='DDESONN'),check.names=FALSE)
write.csv(head(unlabeled[p$features],20),file.path(out,'compact-unlabeled-prediction-example.csv'),row.names=FALSE,na='')
labeled <- read.csv(file.path(out,'compact-original-test-example.csv'),check.names=FALSE)
unlabeled <- read.csv(file.path(out,'compact-unlabeled-prediction-example.csv'),check.names=FALSE)
a <- h$wb_new_predictions(bundle,unlabeled);b<-h$wb_new_predictions(loaded,unlabeled)
stopifnot(isTRUE(all.equal(a,b)))
write.csv(b,file.path(out,'expected-predictions.csv'),row.names=FALSE)
report <- h$wb_prediction_report(loaded,labeled)
stopifnot(report$matched_rows==20,report$overlap[[2]][1]==0,report$overlap[[2]][2]==0,report$overlap[[2]][3]==20)
write.csv(report$metrics,file.path(out,'example-evaluation.csv'),row.names=FALSE)
metrics<-do.call(rbind,lapply(names(bundle$evaluation),function(n)cbind(Split=n,bundle$evaluation[[n]]$metrics)))
write.csv(metrics,file.path(out,'saved-evaluation.csv'),row.names=FALSE)
print(metrics);print(report$metrics);cat('Selected epoch:',bundle$selected_epoch,'\nBytes:',file.info(file.path(out,name))$size,'\n')
